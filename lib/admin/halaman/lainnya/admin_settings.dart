            Log.info(
              'Mode pemeliharaan: ${settings?.maintenanceMode ? "Aktif" : "Nonaktif"}, Info: ${settings?.maintenanceInfo.isNotEmpty ? settings?.maintenanceInfo : "(kosong)"}',
